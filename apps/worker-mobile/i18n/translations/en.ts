/** Nested string leaf type — keeps catalog shape without locking Greek to English literals. */
type DeepStringLeaves<T> = {
  readonly [K in keyof T]: T[K] extends string ? string : DeepStringLeaves<T[K]>;
};

export type TranslationCatalog = DeepStringLeaves<typeof en>;
