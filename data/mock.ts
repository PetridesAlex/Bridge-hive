function shift(
  partial: Omit<
    Shift,
    | 'marketId'
    | 'currency'
    | 'professionalRoleId'
    | 'professionalRoleName'
    | 'requirements'
    | 'filledPositions'
    | 'remainingPositions'
  > & {
    filledPositions?: number;
    remainingPositions?: number;
    requirements?: string[];
    professionalRoleId?: string;
    professionalRoleName?: string;
  },
): Shift {
  const required = partial.requiredWorkers;
  const filled = partial.filledPositions ?? 0;
  return {
    marketId: M,
    currency: 'EUR',
    professionalRoleId: partial.professionalRoleId ?? 'role_rn',
    professionalRoleName: partial.professionalRoleName ?? 'Registered Nurse',
    requirements: partial.requirements ?? sharedRequirements,
    filledPositions: filled,
    remainingPositions: partial.remainingPositions ?? required - filled,
    ...partial,
  };
}

